function countWords(text: string): number {
  return text.split(/\s+/).filter((w) => w.length > 0).length;
}

async function main() {
  console.log("📖 Starting chapter seed...\n");

  for (const novelData of sampleChapters) {
    const novel = await prisma.novel.findUnique({
      where: { slug: novelData.novelSlug },
      select: { id: true, title: true },
    });

    if (!novel) {
      console.log(`⚠️ Novel "${novelData.novelSlug}" not found, skipping...`);
      continue;
    }

    console.log(`📚 Seeding chapters for: ${novel.title}`);

    for (const chapter of novelData.chapters) {
      const existing = await prisma.chapter.findFirst({
        where: {
          novelId: novel.id,
          number: chapter.number,
        },
      });

      if (existing) {
        console.log(`   ✓ Chapter ${chapter.number} already exists, skipping...`);
        continue;
      }

      const wordCount = countWords(chapter.content);

      await prisma.chapter.create({
        data: {
          novelId: novel.id,
          number: chapter.number,
          title: chapter.title,
          content: chapter.content,
          wordCount,
        },
      });

      console.log(`   ✅ Created: ${chapter.title} (${wordCount} words)`);
    }

    console.log("");
  }

  console.log("✨ Chapter seed completed!");
}

main()
  .catch((e) => {
    console.error("❌ Seed error:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
